#!/usr/bin/env node
/* Genera supabase/schema.sql con tablas, políticas RLS y datos semilla
   a partir de data/products.js, data/paquetes.js y data/slider.js.
   Uso:  node scripts/generate-supabase-sql.js */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

function loadDataFile(rel) {
  const code = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const sandbox = { window: {} };
  new Function('window', code)(sandbox.window);
  return sandbox.window;
}

const productsWin = loadDataFile('data/products.js');
const paquetesWin = loadDataFile('data/paquetes.js');
const slidesWin = loadDataFile('data/slider.js');

const products = productsWin.MAGNUM_PRODUCTS || [];
const paquetes = paquetesWin.MAGNUM_PAQUETES || [];
const slides = slidesWin.MAGNUM_SLIDES || [];

// Literal SQL con dollar-quoting (maneja comillas, saltos de línea y acentos)
function s(v) {
  let t = String(v == null ? '' : v);
  t = t.replace(/\$\$/g, '$ $');
  return '$$' + t + '$$';
}
function arr(a) {
  if (!a || !a.length) return "'{}'::text[]";
  return 'ARRAY[' + a.map(x => "'" + String(x).replace(/'/g, "''") + "'").join(', ') + ']::text[]';
}
function bool(b) { return b ? 'true' : 'false'; }

let sql = '';
sql += '-- ============================================================\n';
sql += '-- MAGNUM GUNS & AMMO SHOP — Esquema Supabase\n';
sql += '-- Pegar este archivo completo en: Supabase → SQL Editor → Run\n';
sql += '-- ============================================================\n\n';

sql += `-- ----- Tablas -----
create table if not exists products (
  id int generated by default as identity primary key,
  name text not null,
  slug text,
  brand text,
  category text,
  caliber text,
  image text,
  gallery text[] default '{}',
  short_desc text,
  full_desc text
);

create table if not exists paquetes (
  id int generated by default as identity primary key,
  title text not null,
  price text,
  items text[] default '{}',
  featured boolean default false,
  sort_order int default 0
);

create table if not exists slides (
  id int generated by default as identity primary key,
  kicker text,
  title text,
  accent text,
  body text,
  image text,
  btn1_text text,
  btn1_url text,
  btn2_text text,
  btn2_url text,
  sort_order int default 0,
  active boolean default true
);

-- ----- Row Level Security -----
alter table products enable row level security;
alter table paquetes enable row level security;
alter table slides enable row level security;

-- Lectura pública
drop policy if exists "public read products" on products;
create policy "public read products" on products for select using (true);
drop policy if exists "public read paquetes" on paquetes;
create policy "public read paquetes" on paquetes for select using (true);
drop policy if exists "public read slides" on slides;
create policy "public read slides" on slides for select using (true);

-- Escritura solo para usuarios autenticados (el admin)
drop policy if exists "admin write products" on products;
create policy "admin write products" on products for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
drop policy if exists "admin write paquetes" on paquetes;
create policy "admin write paquetes" on paquetes for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
drop policy if exists "admin write slides" on slides;
create policy "admin write slides" on slides for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

`;

sql += '\n-- ----- Datos semilla: productos -----\n';
sql += 'delete from products;\n';
products.forEach(p => {
  sql += `insert into products (id, name, slug, brand, category, caliber, image, gallery, short_desc, full_desc) values (${p.id}, ${s(p.name)}, ${s(p.slug)}, ${s(p.brand)}, ${s(p.category)}, ${s(p.caliber)}, ${s(p.image)}, ${arr(p.gallery)}, ${s(p.desc)}, ${s(p.fullDesc || p.desc)});\n`;
});
sql += "select setval(pg_get_serial_sequence('products','id'), (select max(id) from products));\n";

sql += '\n-- ----- Datos semilla: paquetes -----\n';
sql += 'delete from paquetes;\n';
paquetes.forEach(p => {
  sql += `insert into paquetes (id, title, price, items, featured, sort_order) values (${p.id}, ${s(p.title)}, ${s(p.price)}, ${arr(p.items)}, ${bool(p.featured)}, ${p.sort_order || 0});\n`;
});
sql += "select setval(pg_get_serial_sequence('paquetes','id'), (select max(id) from paquetes));\n";

sql += '\n-- ----- Datos semilla: slides -----\n';
sql += 'delete from slides;\n';
slides.forEach(p => {
  sql += `insert into slides (id, kicker, title, accent, body, image, btn1_text, btn1_url, btn2_text, btn2_url, sort_order, active) values (${p.id}, ${s(p.kicker)}, ${s(p.title)}, ${s(p.accent)}, ${s(p.text)}, ${s(p.image)}, ${s(p.btn1_text)}, ${s(p.btn1_url)}, ${s(p.btn2_text)}, ${s(p.btn2_url)}, ${p.sort_order || 0}, ${bool(p.active !== false)});\n`;
});
sql += "select setval(pg_get_serial_sequence('slides','id'), (select max(id) from slides));\n";

const outDir = path.join(ROOT, 'supabase');
fs.mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, 'schema.sql');
fs.writeFileSync(outPath, sql, 'utf8');

console.log('✔ Generado ' + outPath);
console.log('  - productos: ' + products.length);
console.log('  - paquetes:  ' + paquetes.length);
console.log('  - slides:    ' + slides.length);
